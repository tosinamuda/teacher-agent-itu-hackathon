"""Which of her student activities set work — read, then stamped into the data.

`work_the_step_sets` classified the Student Activity column with a regex: the Gagné
coder's `elicit_performance` rule. That is a derivation standing in for structure the
transcription does not carry, and a study input should not be a regex verdict on prose
when the population is small enough to read.

It is: **18 activities across the cohort's 17 core steps.** Each was read against its
whole step sequence, and the verdicts live in `student_work.json` beside the coder's
own so a disagreement is visible rather than absorbed.

One disagreement stands. `step-t3w02-02` / *"identify their properties"* codes as
performance and is not work set: she draws the shapes, the class answers, she writes the
properties up — oral answering inside her exposition. As a task statement it is also
unresolvable, because "their" means shapes on a board no generator can see.

`stamp` writes each verdict onto the activity in the pinned eval set, so the study's
plans carry the reading and nothing downstream has to know this file exists. A plan
without the flag — production, or a lesson nobody has read yet — still falls back to
the coder, which is why `unclassified` exists to name that case rather than let it pass.

    uv run python -m experiments.h1_condition_eval.student_work
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
CLASSIFICATION_PATH = HERE / "student_work.json"
EVAL_SET_PATH = HERE / "eval_set.json"


def verdicts() -> dict[tuple[str, int], bool]:
    """Every read verdict, keyed by the activity it belongs to."""
    loaded = json.loads(CLASSIFICATION_PATH.read_text(encoding="utf-8"))
    return {
        (str(row["step_id"]), int(row["activity_index"])): bool(row["sets_work"])
        for row in loaded["activities"]
    }


def _student_activities(plan: dict[str, Any]) -> list[tuple[str, int, dict[str, Any]]]:
    return [
        (str(step.get("step_id")), index, activity)
        for step in plan.get("steps") or []
        if step.get("step_kind") == "core"
        for index, activity in enumerate(step.get("activities") or [])
        if str(activity.get("who")) == "student"
    ]


def unclassified() -> list[tuple[str, int, str]]:
    """Cohort activities no one has read — the list that must be empty before a run."""
    read = verdicts()
    loaded = json.loads(EVAL_SET_PATH.read_text(encoding="utf-8"))
    return [
        (step_id, index, str(activity.get("what")))
        for case in loaded["cases"]
        for step_id, index, activity in _student_activities(case["plan"])
        if (step_id, index) not in read
    ]


def stamp() -> int:
    """Write every read verdict onto its activity in the pinned eval set."""
    if missing := unclassified():
        raise SystemExit(
            f"{len(missing)} student activities are unread: {missing}. Read each against "
            "its step and add a verdict to student_work.json before stamping."
        )
    read = verdicts()
    loaded = json.loads(EVAL_SET_PATH.read_text(encoding="utf-8"))
    stamped = 0
    for case in loaded["cases"]:
        for step_id, index, activity in _student_activities(case["plan"]):
            activity["sets_work"] = read[(step_id, index)]
            stamped += 1
    EVAL_SET_PATH.write_text(json.dumps(loaded, indent=2) + "\n", encoding="utf-8")
    return stamped


SHEET_PATH = HERE / "STUDENT-WORK-CONFIRMATION.md"

_PREAMBLE = """# Did she set this work? — confirmation sheet

Generated by `uv run python -m experiments.h1_condition_eval.student_work`.

`student_tasks` is the thinnest key C1 carries, and where her plan has no question text
the verdict below is what decides whether the key is delivered at all. Each row was read
against its whole step sequence rather than pattern-matched, and the coder's own answer
is beside it so a disagreement is visible.

**What to check.** For each row, read her page for that step and tick the box if the
verdict matches what she wrote. The rows that matter most are the ones marked
**decides delivery** — those steps have no question block, so this verdict alone decides
whether C1 receives anything for them.

When a row is confirmed, set `confirmed_against_source_page` in `student_work.json` and
regenerate this sheet. Stamping the verdicts into the eval set is a separate, deliberate
step: `python -m experiments.h1_condition_eval.student_work`.
"""


def sheet() -> str:
    """The 18 rows a researcher checks against her pages."""
    loaded = json.loads(CLASSIFICATION_PATH.read_text(encoding="utf-8"))
    plans = {
        str(step.get("step_id")): step
        for case in json.loads(EVAL_SET_PATH.read_text(encoding="utf-8"))["cases"]
        for step in case["plan"].get("steps") or []
    }
    lines = [_PREAMBLE]
    for row in loaded["activities"]:
        step = plans.get(str(row["step_id"]), {})
        decides = (
            not any(block.get("type") == "practice" for block in step.get("blocks") or [])
            and row["sets_work"]
        )
        flag = " — **decides delivery**" if decides else ""
        agree = "" if row["agrees_with_coder"] else "  ⚠ **differs from the coder**"
        tick = "x" if row["confirmed_against_source_page"] else " "
        lines.append(f"\n## {row['step_id']} · activity {row['activity_index']}{flag}\n")
        lines.append(f"> {row['what']}\n")
        lines.append(
            f"**Read as:** {'work she set' if row['sets_work'] else 'not work set'}"
            f" — {row['why']}{agree}\n"
        )
        lines.append(f"**Coder says:** `{row['coder_says'] or 'no code'}`\n")
        lines.append("**Her step, in order:**\n")
        for activity in step.get("activities") or []:
            lines.append(f"- *{activity.get('who')}* — {activity.get('what')}")
        lines.append(f"\n- [{tick}] confirmed against her page\n")
    return "\n".join(lines) + "\n"


def main() -> int:
    SHEET_PATH.write_text(sheet(), encoding="utf-8")
    print(f"wrote {SHEET_PATH.name}")
    print(f"stamped {stamp()} student activities into {EVAL_SET_PATH.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
