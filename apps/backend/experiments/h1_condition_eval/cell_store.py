"""One generated cell on disk, written when it is made rather than when the run ends.

A run used to hold every cell in memory until all 72 were done, so a grid stopped at
hour one lost hour one. A cell is a lesson, a condition and a draw — the unit the whole
analysis is built from — so it is also the right unit to save and to resume from.

The arm is stored beside the rows and checked on the way back in. Two cells generated
under different models, generators or context variants answer different questions, and
a run that silently mixed them would look exactly like a run that did not.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def write_cell(path: Path, arm: dict[str, object], rows: list[dict[str, Any]]) -> None:
    """Save one cell atomically: a temporary file, then a rename."""
    path.parent.mkdir(parents=True, exist_ok=True)
    scratch = path.with_suffix(".partial")
    scratch.write_text(
        json.dumps({"arm": arm, "rows": rows}, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    scratch.replace(path)


def read_cell(path: Path, arm: dict[str, object]) -> list[dict[str, Any]] | None:
    """A finished cell's rows, or None if this run has to generate them."""
    if not path.exists():
        return None
    saved = json.loads(path.read_text(encoding="utf-8"))
    if saved.get("arm") != arm:
        raise SystemExit(
            f"{path.name} was generated by a different arm. Delete {path.parent} to "
            f"regenerate, or run under a new --label."
        )
    rows: list[dict[str, Any]] = saved["rows"]
    return rows
