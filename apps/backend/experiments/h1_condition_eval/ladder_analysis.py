"""The whole ladder from one run: what the plan adds, then the note, then repair.

`final_analysis` reports the study's endpoint — C1 against C0, across two runs. This
reports the rungs, which only a run carrying all four conditions can show:

* **C1 − C0** — what her lesson plan adds to the objectives alone.
* **C2 − C1** — what her NOTE adds once the plan is already there.
* **C3 − C2** — what validation and repair add on top of both.

Each is a paired difference over the same six lessons and the same draws, so the three
are directly comparable: a rung that costs more than it returns says so here.

    uv run python -m experiments.h1_condition_eval.ladder_analysis c0c3-deepseek-native
"""

from __future__ import annotations

import argparse
import statistics

from experiments.h1_condition_eval.condition_trace.scores import DIMENSIONS, LABELS
from experiments.h1_condition_eval.config import RUNS_DIR
from experiments.h1_condition_eval.final_analysis import (
    TERMS,
    _difference_error,
    _judged,
    _sign,
    _topics,
    _verdict,
)

#: The rungs, each named by what it adds. Order matters: every step is against the one
#: below it, so a reader can add them and get C3 − C0.
STEPS = (
    ("C0", "C1", "her lesson plan"),
    ("C1", "C2", "her note"),
    ("C2", "C3", "validation and repair"),
)
CONDITIONS = ("C0", "C1", "C2", "C3")


def _ladder_table(
    means: dict[str, dict[tuple[str, str], float]], lessons: list[str], lesson: str | None = None
) -> list[str]:
    """Four conditions and the three differences between them, one row per rubric."""
    out = [
        "| rubric | C0 | C1 | C2 | C3 | **C1−C0** | C2−C1 | C3−C2 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]

    def at(cond: str, dim: str) -> float:
        if lesson is not None:
            return means[cond][(lesson, dim)]
        return statistics.fmean(means[cond][(x, dim)] for x in lessons)

    for dim in DIMENSIONS:
        mark = "**" if dim == "taught_lesson_alignment" else ""
        cells = " ".join(f"{at(c, dim):.2f} |" for c in CONDITIONS)
        deltas = " ".join(
            f"{_sign(at(hi, dim) - at(lo, dim))} |"
            if i
            else f"**{_sign(at(hi, dim) - at(lo, dim))}** |"
            for i, (lo, hi, _) in enumerate(STEPS)
        )
        out.append(f"| {mark}{LABELS[dim]}{mark} | {cells} {deltas}")
    return out


def _reasons(why: dict, lesson: str, dim: str) -> list[str]:
    return [
        f"- **{cond}** — {text}"
        for cond, w in why.items()
        for text in dict.fromkeys(w[(lesson, dim)])
    ]


def report(run: str) -> str:
    judged = {c: _judged(run, c) for c in CONDITIONS}
    means = {c: judged[c][0] for c in CONDITIONS}
    whys = {c: judged[c][1] for c in CONDITIONS}
    raws = {c: judged[c][2] for c in CONDITIONS}
    lessons = sorted({lesson for lesson, _ in means["C0"]})
    topics = _topics()

    out = [
        "# The ladder, rung by rung",
        "",
        f"Generated by `experiments.h1_condition_eval.ladder_analysis`; do not edit. Run "
        f"`{run}`. Six lessons, four conditions, three draws per cell, two Sonnet 4.6 passes "
        "per candidate, so every figure is the mean of six judgments. Scores are 1–5.",
        "",
        "**C0** receives the objectives alone. **C1** adds her lesson plan — every field it "
        "holds, including her narration, activities and step titles — and never her note. "
        "**C2** adds the note. **C3** adds a validation pass that criticises the draft and "
        "repairs what it finds.",
        "",
        "So the three differences answer three different questions, and they are paired over "
        "the same lessons and the same draws:",
        "",
        "| step | what it adds | the question it answers |",
        "|---|---|---|",
        "| **C1 − C0** | her lesson plan | does knowing the lesson's design help? |",
        "| C2 − C1 | her note | does the taught content add more on top? |",
        "| C3 − C2 | validation and repair | does checking the draft earn its cost? |",
        "",
        "Each difference is reported beside the spread of the draws it was averaged from. A "
        "difference smaller than that disagreement is marked not separable rather than "
        "printed as a result. It is a spread, not a significance test.",
        "",
        "## Across the board — all six lessons pooled",
        "",
    ]
    out += _ladder_table(means, lessons)
    out += ["", "| step | rubric | difference | reading |", "|---|---|---:|---|"]
    for lo, hi, adds in STEPS:
        for dim in DIMENSIONS:
            a = statistics.fmean(means[lo][(x, dim)] for x in lessons)
            b = statistics.fmean(means[hi][(x, dim)] for x in lessons)
            err = _difference_error(
                [s for x in lessons for s in raws[lo][(x, dim)]],
                [s for x in lessons for s in raws[hi][(x, dim)]],
            )
            out.append(
                f"| {hi} − {lo} ({adds}) | {LABELS[dim]} | {_sign(b - a)} | "
                f"{_verdict(b - a, err)} |"
            )
    out.append("")

    for lesson in lessons:
        out += [f"## {lesson} — {topics.get(lesson, '')}", "", f"*{TERMS[lesson]}*", ""]
        out += _ladder_table(means, lessons, lesson)
        out.append("")
        for dim in DIMENSIONS:
            scores = ", ".join(f"{c} {means[c][(lesson, dim)]:.2f}" for c in CONDITIONS)
            out += [f"### {LABELS[dim]} — {scores}", ""]
            for lo, hi, adds in STEPS:
                a, b = means[lo][(lesson, dim)], means[hi][(lesson, dim)]
                err = _difference_error(raws[lo][(lesson, dim)], raws[hi][(lesson, dim)])
                out.append(f"- **{hi} − {lo}** ({adds}): {_sign(b - a)} — {_verdict(b - a, err)}")
            out += ["", "The judge's own reasons, deduplicated:", ""]
            out += _reasons(whys, lesson, dim)
            out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run", help="a run carrying C0, C1, C2 and C3")
    args = parser.parse_args()
    out = RUNS_DIR / f"LADDER-{args.run}.md"
    out.write_text(report(args.run), encoding="utf-8")
    print(f"  {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
