"""Report the harness bake-off on the rubric the study is judged on.

    uv run python -m experiments.h1_condition_eval.bakeoff_judge \\
        experiments/h1_condition_eval/HARNESS-BAKEOFF-<date>.json \\
        --judge-model bedrock/converse/global.anthropic.claude-sonnet-4-6

The packs are the ones the bake-off kept, so this rates the artefact that was screened
rather than a fresh draw of it. Everything about how they are rated — two passes per pack,
one candidate per call, the harness read out of the file — is in `harness_rating`.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import statistics
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

from experiments.h1_condition_eval.collect_judgments import DIMENSIONS
from experiments.h1_condition_eval.harness_rating import (
    PASSES,
    Rated,
    artefact,
    draw_floor,
    harnesses,
    judge_floor,
    pack_movements,
    passes_per_pack,
    rate,
    summarise,
)
from experiments.h1_condition_eval.judge import DEFAULT_CONCURRENCY, build_judge_lm

HERE = Path(__file__).parent
SHORT = {dimension: dimension.split("_")[0] for dimension in DIMENSIONS}
"""Column headings. The full criterion ids are in `H1_RUBRIC` and in the packet itself."""


def report(rated: list[Rated], loaded: dict[str, Any], *, source: str, judge_model: str) -> str:
    """The table, then what it is allowed to conclude."""
    summary = summarise(rated)
    ranked = sorted(summary.items(), key=lambda item: -item[1]["rubric_mean"])
    declared = harnesses(loaded)
    floor = max(judge_floor(rated), draw_floor(rated))
    margin = _margin(ranked)
    lines = [
        f"# Harness bake-off, judged — {datetime.now(timezone.utc).date().isoformat()}",
        "",
        "Generated by `uv run python -m experiments.h1_condition_eval.bakeoff_judge`.",
        f"Packs: `{source}` — {len(rated)} rated, "
        f"{loaded.get('repeats', '?')} draws per lesson over "
        f"`{loaded.get('selection_set', 'the selection set')}`, condition "
        f"{loaded.get('condition', '?')}. Every pack held out from the frozen eval set.",
        "",
        f"Judge: `{judge_model}`, {passes_per_pack(rated)} independent ratings per pack, "
        "one candidate per",
        "call, blinded behind an opaque id. Scored on the study's own H1 rubric, 1-5.",
        "",
        "| Candidate | framework | loop | version | packs | rubric mean | "
        + " | ".join(SHORT[d] for d in DIMENSIONS)
        + " |",
        "| --- | --- | --- | --- | ---: | ---: |" + " ---: |" * len(DIMENSIONS),
    ]
    for name, values in ranked:
        harness = declared[name]
        lines.append(
            f"| `{name}` | {harness['framework']} | {harness['loop']} | "
            f"{harness['framework_version']} | {values['packs']:.0f} | "
            f"**{values['rubric_mean']:.2f}** | "
            + " | ".join(f"{values[d]:.2f}" for d in DIMENSIONS)
            + " |"
        )
    return "\n".join(lines + _verdict(ranked, rated, margin, floor) + _caveats()) + "\n"


def _margin(ranked: list[tuple[str, dict[str, float]]]) -> float:
    if len(ranked) < 2:
        return 0.0
    return ranked[0][1]["rubric_mean"] - ranked[1][1]["rubric_mean"]


def _verdict(
    ranked: list[tuple[str, dict[str, float]]], rated: list[Rated], margin: float, floor: float
) -> list[str]:
    winner, last = ranked[0], ranked[-1]
    runner_up = ranked[1] if len(ranked) > 1 else ranked[0]
    spread = winner[1]["rubric_mean"] - last[1]["rubric_mean"]
    movements = pack_movements(rated)
    moved = [movement for movement in movements if movement > 0]
    return [
        "",
        "## Verdict",
        "",
        f"Leader: **`{winner[0]}`** at {winner[1]['rubric_mean']:.2f}, ahead of "
        f"`{runner_up[0]}` by **{margin:.2f}**.",
        "",
        f"The margin a winner must clear is **{floor:.2f}** — the larger of what the judge "
        f"does to a whole row when nothing in it changed ({judge_floor(rated):.2f}) and what "
        f"one harness does to its own row when only the draw changed "
        f"({draw_floor(rated):.2f}). Both are measured on the candidate means this table "
        f"ranks, not on single packs, which are a level finer than anything compared here. "
        + (
            "This margin clears it, so the lead is a difference between harnesses."
            if margin > floor
            else "**This margin does not clear it**, so the top of the table is a tie and "
            "no winner is named."
        ),
        "",
        f"Top to bottom the table spreads **{spread:.2f}**, which "
        + (
            "clears the floor: the table separates a top group from a bottom group even "
            "where it cannot rank within them."
            if spread > floor
            else "does NOT clear it either. Nothing here separates from anything else."
        ),
        "",
        "## What the judge did to prose that did not change",
        "",
        f"{len(moved)} of {len(movements)} packs were scored differently on the second "
        f"reading, by up to {max(movements, default=0.0):.2f} and by "
        f"{statistics.fmean(moved) if moved else 0.0:.2f} on average when they moved at all. "
        "Twelve of those average out to the row movement in the floor above; this is what "
        "they look like one pack at a time, and it is why a single rating is not a score.",
    ]


def _caveats() -> list[str]:
    return [
        "",
        "## What this does not cover",
        "",
        "One judge, not a panel. Two ratings bound what this judge does to identical prose;",
        "they say nothing about what a different judge, or a human rater, would do with it.",
        "",
        "The lessons are constructed. They reproduce the structural shapes the cohort audit",
        "found in the teacher's real plans, and nothing chosen on them has seen the frozen",
        "data — but a harness chosen here is chosen on constructed lessons.",
        "",
        "The frameworks are bounded in their own units: dspy and ADK cap model turns,",
        "langgraph caps graph supersteps, and deepagents spends supersteps on middleware the",
        "others do not have. Each arm names its own cut-off `iteration_limit`, but only the",
        "study runner opens a trace window to catch it — this screening pass does not, so a",
        "composition truncated by its cap reaches the judge as a short section and nothing",
        "in this table says which ones those were.",
    ]


def restore(path: Path) -> tuple[list[Rated], str]:
    """The ratings a previous pass wrote, so the report can be rebuilt without re-rating.

    Re-reporting is not re-measuring: the judgments are the measurement and they are kept.
    Changing how a floor is computed should not cost another two hundred judge calls, and
    should not silently rate a different draw either.
    """
    written = json.loads(path.read_text(encoding="utf-8"))
    return [
        Rated(
            candidate=item["candidate"],
            lesson=item["lesson"],
            draw=item["draw"],
            packet_id=item["packet_id"],
            passes=tuple(dict(marks) for marks in item["passes"]),
        )
        for item in written["rated"]
    ], str(written["judge_model"])


def main() -> int:
    load_dotenv()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("packs", type=Path, help="the JSON the bake-off wrote beside its report")
    parser.add_argument("--judge-model", help="must not be the generator's model")
    parser.add_argument("--concurrency", type=int, default=DEFAULT_CONCURRENCY)
    parser.add_argument(
        "--passes",
        type=int,
        default=PASSES,
        help="ratings per pack; two is the least that measures the judge",
    )
    parser.add_argument(
        "--rated",
        type=Path,
        default=None,
        help="rebuild the report from a written HARNESS-JUDGED json instead of rating again",
    )
    args = parser.parse_args()

    loaded = artefact(args.packs)
    # Before any judge call: an artefact that cannot say what produced its packs is not
    # worth rating, and finding that out after 200 calls is finding it out too late.
    declared = harnesses(loaded)
    if args.rated:
        rated, judge_model = restore(args.rated)
    elif args.judge_model:
        judge_model = args.judge_model
        lm = build_judge_lm(judge_model)
        rated = asyncio.run(
            rate(
                loaded,
                source=args.packs.name,
                lm=lm,
                concurrency=args.concurrency,
                passes=args.passes,
            )
        )
    else:
        parser.error("--judge-model is required unless --rated re-reports an existing pass")

    stamped = datetime.now(timezone.utc).date().isoformat()
    out = HERE / f"HARNESS-JUDGED-{stamped}.md"
    out.write_text(
        report(rated, loaded, source=args.packs.name, judge_model=judge_model),
        encoding="utf-8",
    )
    out.with_suffix(".json").write_text(
        json.dumps(
            {
                "packs": args.packs.name,
                "judge_model": judge_model,
                "passes_per_pack": passes_per_pack(rated),
                "arms": declared,
                "judge_floor": judge_floor(rated),
                "draw_floor": draw_floor(rated),
                "summary": summarise(rated),
                "rated": [asdict(item) for item in rated],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"\nwrote {out.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
