"""Does any plan-native field carry the note? Measured, per sentence, in the repo.

C1 is defined as the plan without the note, and its gates were set by reading the
data once: a comment recorded note material in four steps' ``content`` and the
field was withheld. The corpus has been rebuilt since and the comment was not,
so the claim outlived the data it described. This replaces the reading with a
measurement anyone can rerun.

For every core step, every sentence of the two plan-native narrative fields —
``content`` and each ``activities[].what`` — is looked for in the note the
model receives at C2 (``step.note``, the text ``lesson_content`` is projected
from). A sentence found there is note material inside a plan field, and that
is the leak the C1 gate exists to prevent.

    uv run python -m experiments.h1_condition_eval.source_boundary
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from app.shared.session_plan_view import SessionPlanStepView, SessionPlanView
from experiments.h1_condition_eval.dataset import EVAL_SET_PATH

HERE = Path(__file__).resolve().parent
REPORT = HERE / "SOURCE-BOUNDARY.md"

_SPLIT = re.compile(r"(?<=[.!?])\s+|\n{2,}")
_MIN_SENTENCE = 25


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


def _sentences(text: str) -> list[str]:
    return [s for part in _SPLIT.split(text) if len(s := _norm(part)) >= _MIN_SENTENCE]


@dataclass(frozen=True)
class StepAudit:
    lesson: str
    step_id: str
    title: str
    content_sentences: int
    content_in_note: int
    activity_sentences: int
    activities_in_note: int
    title_stands_in: bool

    @property
    def leaks(self) -> int:
        return self.content_in_note + self.activities_in_note


def audit_step(lesson: str, step: SessionPlanStepView) -> StepAudit:
    note = _norm(step.note or "")
    title = (step.title or "").strip()
    content = (step.content or "").strip()
    stands_in = bool(content) and content == title
    content_sentences = [] if stands_in else _sentences(content)
    activity_sentences = [s for a in step.activities for s in _sentences(str(a.get("what") or ""))]
    return StepAudit(
        lesson=lesson,
        step_id=step.step_id,
        title=title,
        content_sentences=len(content_sentences),
        content_in_note=sum(s in note for s in content_sentences) if note else 0,
        activity_sentences=len(activity_sentences),
        activities_in_note=sum(s in note for s in activity_sentences) if note else 0,
        title_stands_in=stands_in,
    )


def audit() -> list[StepAudit]:
    cases = json.loads(EVAL_SET_PATH.read_text())["cases"]
    return [
        audit_step(case["lesson"], step)
        for case in sorted(cases, key=lambda c: c["lesson"])
        for step in SessionPlanView.model_validate(case["plan"]).steps
        if step.step_kind == "core"
    ]


def report(rows: list[StepAudit]) -> str:
    leaks = sum(r.leaks for r in rows)
    content_total = sum(r.content_sentences for r in rows)
    activity_total = sum(r.activity_sentences for r in rows)
    stand_ins = [r for r in rows if r.title_stands_in]
    lines = [
        "# Source boundary — plan-native fields against the note",
        "",
        "Generated by `experiments.h1_condition_eval.source_boundary`; do not edit.",
        "",
        f"**{len(rows)} core steps.** `content` carries {content_total} sentences and "
        f"`activities` {activity_total}; **{leaks} of them appear in the note** the model "
        "receives at C2. "
        + (
            f"On {len(stand_ins)} step(s) she wrote no narration and the researcher-supplied "
            "title stands in for `content`: "
            + ", ".join(f"{r.lesson} {r.step_id}" for r in stand_ins)
            + "."
            if stand_ins
            else ""
        ),
        "",
        "| lesson | step | `content` sentences | in note | `activities` sentences | in note |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        content = "(title stands in)" if r.title_stands_in else str(r.content_sentences)
        lines.append(
            f"| {r.lesson} | {r.step_id} | {content} | {r.content_in_note} | "
            f"{r.activity_sentences} | {r.activities_in_note} |"
        )
    lines += [
        "",
        "A sentence is looked for after whitespace folding and case folding, at 25 characters "
        "or more. This catches a copied sentence; it does not catch a paraphrase, and the "
        "gates on `content` and `activities` are not evidence-based on that question.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    rows = audit()
    REPORT.write_text(report(rows), encoding="utf-8")
    leaks = sum(r.leaks for r in rows)
    print(f"  {len(rows)} core steps, {leaks} plan-field sentence(s) found in the note")
    print(f"  {REPORT.relative_to(HERE)}")
    return 1 if leaks else 0


if __name__ == "__main__":
    raise SystemExit(main())
