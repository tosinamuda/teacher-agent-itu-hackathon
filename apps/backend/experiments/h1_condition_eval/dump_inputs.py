"""Write out what each condition actually sends the model, per lesson.

The schema says what a condition MAY carry; only the rendered payload says what it does.
Every leak found so far was invisible in the schema and obvious here — evaluation answers
arriving as "(expected answer: 32cm)", her bare step label offered as the citable name for
her note, an ``instructional_type`` of "explain_only" sitting beside instructional_events
["present_content", "provide_learning_guidance"]. So this regenerates rather than being
kept by hand.

    uv run python -m experiments.h1_condition_eval.dump_inputs
"""

from __future__ import annotations

import json
from pathlib import Path

from app.domains.artefacts.types.post_class_review_pack.application.request.base.builder import (
    BaseReviewPackRequestBuilder,
)
from app.domains.artefacts.types.post_class_review_pack.application.request.schemas import (
    BaseReviewPackRequest,
)
from app.domains.artefacts.types.post_class_review_pack.application.request.sources import (
    LessonSources,
)
from app.domains.artefacts.types.post_class_review_pack.infrastructure.dspy.contracts.write_section import (  # noqa: E501
    signature_for,
)
from app.domains.artefacts.types.post_class_review_pack.infrastructure.dspy.prompt_projection import (  # noqa: E501
    prompt_lesson,
    prompt_unit,
)
from app.domains.experiments.domain.types import ConditionCode, Hypothesis
from app.domains.experiments.review_pack_study.conditions.profiles import profile_for
from app.shared.session_plan_view import SessionPlanView
from experiments.h1_condition_eval.dataset import EVAL_SET_PATH

OUTPUT_PATH = Path(__file__).parent / "C0-C1-INPUTS.md"
CONDITIONS = (ConditionCode.C0, ConditionCode.C1)

PREAMBLE = """# What C0 and C1 actually send the model

Generated by `dump_inputs.py` from the frozen eval set, through `prompt_lesson` and
`prompt_unit` — the same two functions the generator calls — so what is printed below is
the payload, not a second rendering of it. Dumping the models directly is how
`entry_behaviour: []` stayed invisible in this file while C0 was reading it.

**C0** — the curriculum specification: objectives, subject, grade, topic, subtopic.
**C1** — C0 plus the lesson plan's design fields, enumerated in `C1-DEFINITION.md`.

Sections are generated one unit at a time by independent concurrent calls, so each
`unit_context` below is one LM call, and every call in a lesson sees the same
`lesson_context`. A field with no source in a given plan is absent for that lesson;
nothing is supplied to fill it, which is why the shapes differ between lessons.

---

## The task contract

Chosen by what the profile provides, never by condition label. Both carry the SAME
instructional-events codebook: dspy replaces a parent docstring rather than extending it,
so a codebook on the step-level signature alone would put instructional-design prose in
C1's prompt and none in C0's — and that prose, rather than the lesson plan, could then
explain a C1 advantage. C0 receives the legend and never receives the field.
"""


def _request(
    builder: BaseReviewPackRequestBuilder, plan: SessionPlanView, code: ConditionCode
) -> BaseReviewPackRequest:
    return builder.build(
        session_plan=plan,
        policy=profile_for(Hypothesis.H1, code).generation_policy(),
        sources=LessonSources.unresolved(plan.references),
    )


def _dump_lesson_json(request: BaseReviewPackRequest, indent: int | None = None) -> str:
    """The one place this file serialises a lesson, so it cannot drift from the prompt."""
    return json.dumps(prompt_lesson(request.lesson_context), indent=indent)


def _prompt_chars(request: BaseReviewPackRequest) -> int:
    return len(_dump_lesson_json(request)) + sum(
        len(json.dumps(prompt_unit(unit))) for unit in request.units
    )


def _contract(builder: BaseReviewPackRequestBuilder, plan: SessionPlanView) -> list[str]:
    lines: list[str] = []
    for code in CONDITIONS:
        signature = signature_for(profile_for(Hypothesis.H1, code).generation_policy())
        lines += [
            f"### {code.value} — `{signature.__name__}`\n",
            "```text",
            signature.instructions.strip(),
            "```\n",
        ]
    spec = _request(builder, plan, ConditionCode.C0).artefact_spec
    lines += [
        "### artefact_spec — identical in both conditions\n",
        "```json",
        spec.model_dump_json(indent=2),
        "```\n",
    ]
    return lines


def _lesson(builder: BaseReviewPackRequestBuilder, plan: SessionPlanView, key: str) -> list[str]:
    lines = [f"---\n\n## {key} — {plan.topic}\n"]
    for code in CONDITIONS:
        request = _request(builder, plan, code)
        calls, chars = len(request.units), _prompt_chars(request)
        lines += [
            f"### {code.value} — {calls} call(s), {chars:,} chars\n",
            "**lesson_context** — the same object on every call\n",
            "```json",
            _dump_lesson_json(request, indent=2),
            "```\n",
        ]
        for index, unit in enumerate(request.units, start=1):
            lines += [
                f"**unit_context {index} of {len(request.units)}**\n",
                "```json",
                json.dumps(prompt_unit(unit), indent=2, ensure_ascii=False),
                "```\n",
            ]
    return lines


def main() -> int:
    builder = BaseReviewPackRequestBuilder()
    cases = json.loads(Path(EVAL_SET_PATH).read_text())["cases"]
    plans = {case["lesson"]: SessionPlanView.model_validate(case["plan"]) for case in cases}

    lines = [
        PREAMBLE,
        *_contract(builder, next(iter(plans.values()))),
        "---\n\n## Size, per lesson\n",
        "| lesson | topic | C0 | C1 | ratio | C1 calls |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for key, plan in plans.items():
        c0 = _prompt_chars(_request(builder, plan, ConditionCode.C0))
        c1_request = _request(builder, plan, ConditionCode.C1)
        c1 = _prompt_chars(c1_request)
        lines.append(
            f"| {key} | {plan.topic} | {c0:,} | {c1:,} | {c1 / c0:.1f}x | {len(c1_request.units)} |"
        )
    lines.append("")
    for key, plan in plans.items():
        lines += _lesson(builder, plan, key)

    OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT_PATH} — {len(OUTPUT_PATH.read_text()):,} chars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
