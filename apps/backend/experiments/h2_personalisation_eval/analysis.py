"""P1 − P0, paired per learner, with the judge's reasons under every score.

Every learner is their own control: the same profile is judged against the base pack
and against the pack personalised for them, so the difference is personalisation and
nothing else. The endpoint statistic is a Wilcoxon signed-rank over learners.

``misconception_support`` is excluded wherever the judge marked it inapplicable —
with constructed-response classwork no misconception is coded, so most cells are —
and the report says how many survived rather than averaging placeholders.

The report is committed; the run directories it reads are versioned by DVC. Judge rationales
discuss anonymous learner codes and the packs, which is the analysis the study
exists to produce; the raw scripts and states stay on this machine.

    uv run python -m experiments.h2_personalisation_eval.analysis h2-deepseek-native
"""

from __future__ import annotations

import argparse
import json
import statistics
from itertools import product
from pathlib import Path

from app.domains.evaluation.application.constants import H2_RUBRIC
from experiments.h2_personalisation_eval.rating import DIMENSIONS, RUNS

HERE = Path(__file__).resolve().parent
LABELS = {str(c["criterion_id"]): str(c["label"]) for c in H2_RUBRIC}


def _signed_rank(diffs: list[float]) -> tuple[float | None, int, int]:
    nz = [d for d in diffs if d]
    n = len(nz)
    if not n:
        return None, 0, 0
    absv = sorted(abs(v) for v in nz)
    ranks = [statistics.fmean([i + 1 for i, x in enumerate(absv) if x == abs(v)]) for v in nz]
    w = sum(r * (1 if v > 0 else -1) for v, r in zip(nz, ranks, strict=True))
    hits = sum(
        1
        for signs in product([1, -1], repeat=n)
        if abs(sum(a * b for a, b in zip(signs, ranks, strict=True))) >= abs(w) - 1e-9
    )
    return hits / 2**n, n, sum(1 for v in nz if v > 0)


def _load(run_label: str) -> tuple[list[dict], dict[str, dict]]:
    rating = RUNS / run_label / "rating"
    key = json.loads((rating / "_key.json").read_text())
    by_candidate: dict[str, list[dict]] = {}
    for path in sorted(rating.glob("judgments_pass_*.json")):
        for judgment in json.loads(path.read_text())["judgments"]:
            by_candidate.setdefault(judgment["candidate_id"], []).append(judgment)
    return key, by_candidate


def _cell(judgments: list[dict], dim: str) -> tuple[float | None, list[str]]:
    """Mean score over passes, and every rationale; None where never applicable."""
    scores, reasons = [], []
    for judgment in judgments:
        rating = judgment[dim]
        if dim == "misconception_support" and not rating.get("applicable", True):
            continue
        scores.append(float(rating["score"]))
        if text := str(rating.get("rationale") or "").strip():
            reasons.append(text)
    return (statistics.fmean(scores) if scores else None), reasons


def report(run_label: str) -> str:
    key, judged = _load(run_label)
    learners = sorted({(row["lesson"], row["student"]) for row in key})
    cid = {(row["lesson"], row["student"], row["condition"]): row["candidate_id"] for row in key}
    passes = len(next(iter(judged.values())))

    def cell(lesson: str, student: str, condition: str, dim: str):
        return _cell(judged[cid[(lesson, student, condition)]], dim)

    out = [
        "# P1 − P0: does personalisation fit the pack to the learner?",
        "",
        f"Generated by `experiments.h2_personalisation_eval.analysis`; do not edit. Run "
        f"`{run_label}` — {len(learners)} learners across "
        f"{len({lesson for lesson, _ in learners})} lessons, each judged under P0 (the base "
        f"pack unchanged) and P1 (personalised), {passes} judge pass(es) per candidate. "
        "Scores are 1–5; every learner is their own control.",
        "",
        "## Across the board",
        "",
        "| rubric | P0 | P1 | **P1 − P0** | learners with a state* | p (signed-rank) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for dim in DIMENSIONS:
        pairs = []
        for lesson, student in learners:
            p0, _ = cell(lesson, student, "P0", dim)
            p1, _ = cell(lesson, student, "P1", dim)
            if p0 is not None and p1 is not None:
                pairs.append((p0, p1))
        if not pairs:
            out.append(f"| {LABELS[dim]} | — | — | — | 0 | — |")
            continue
        mean0 = statistics.fmean(p for p, _ in pairs)
        mean1 = statistics.fmean(p for _, p in pairs)
        p_value, nonzero, positive = _signed_rank([b - a for a, b in pairs])
        shown = f"{p_value:.4f}" if p_value is not None else "—"
        out.append(
            f"| {LABELS[dim]} | {mean0:.2f} | {mean1:.2f} | **{mean1 - mean0:+.2f}** | "
            f"{len(pairs)} | {shown} ({positive}/{nonzero} +ve) |"
        )
    out += [
        "",
        "*misconception_support counts only learners the judge scored it applicable for, "
        "in both conditions.",
        "",
    ]

    for lesson, student in learners:
        out += [f"## {lesson} — {student}", ""]
        out += ["| rubric | P0 | P1 | P1 − P0 |", "|---|---:|---:|---:|"]
        for dim in DIMENSIONS:
            p0, _ = cell(lesson, student, "P0", dim)
            p1, _ = cell(lesson, student, "P1", dim)
            if p0 is None or p1 is None:
                out.append(f"| {LABELS[dim]} | n/a | n/a | — |")
            else:
                out.append(f"| {LABELS[dim]} | {p0:.2f} | {p1:.2f} | {p1 - p0:+.2f} |")
        out.append("")
        for dim in DIMENSIONS:
            p0, why0 = cell(lesson, student, "P0", dim)
            p1, why1 = cell(lesson, student, "P1", dim)
            if p0 is None and p1 is None:
                continue
            out.append(f"### {LABELS[dim]}")
            out.append("")
            for label, reasons in (("P0", why0), ("P1", why1)):
                for text in dict.fromkeys(reasons):
                    out.append(f"- **{label}** — {text}")
            out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_label")
    args = parser.parse_args()
    out = HERE / f"H2-ANALYSIS-{args.run_label}.md"
    out.write_text(report(args.run_label), encoding="utf-8")
    print(f"  {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
