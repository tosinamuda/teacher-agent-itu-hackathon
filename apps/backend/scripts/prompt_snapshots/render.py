"""Turn one arm's prepared call into the committed snapshot text.

Everything written here is derived from the call. Nothing is described in prose that the
render does not show, because a hand-written summary beside a generated body is the thing
that goes stale first.
"""

from __future__ import annotations

from scripts.prompt_snapshots.arms import Arm
from scripts.prompt_snapshots.served import ServedArm

HEADER = """# Rendered prompt: {condition}

{description}

Generated by `uv run python -m scripts.prompt_snapshots` — do not edit by hand.
"""

NO_CALL = """
## No model call

This condition sends no prompt: its policy reuses the approved base sections unchanged.
"""

PROVENANCE_HEADER = """# Where each prompt field comes from

Generated by `uv run python -m scripts.prompt_snapshots` — do not edit by hand. Every row is
read out of the projector source, so it cannot drift from the pipeline.

Read a row as: the request-schema **field**, the **builder** keyword that fills it, the plan
attributes its value actually **reads**, and the **store** those attributes are parsed from.
`origin` is `traced` when the value is read from a store, `literal` when the code supplies
it, and `delegated` when another projector owns it.

The link this map does not walk is the last one: which rendered prompt key a field lands
under. That is pinned separately by `test_rendered_arm_differences.py`, from the renders.

**A row with origin `untraced` is a finding.** It means a value reaching the model that this
cannot account for, and `test_prompt_field_provenance.py` fails on one.

"""

CALL_INTRO = """
This is the ChatAdapter message list for one section call, exactly as DSPy sends it.
"""

SERVED_INTRO = """
This is the first turn of the section composer production runs, recorded from the
request it sent to the model. Later turns add the tool results to `history`.
"""


def snapshot_text(arm: Arm) -> str:
    """The full committed snapshot for one arm."""
    parts = [HEADER.format(condition=arm.condition.value, description=arm.description)]
    if arm.call is None:
        return "".join([*parts, NO_CALL])

    parts.append(CALL_INTRO)
    parts.append(f"\nContract: `{arm.call.contract.__name__}`\n")
    parts.append(f"Fields sent: {', '.join(arm.call.signature.input_fields)}\n")
    parts.append(f"Fields expected back: {', '.join(arm.call.signature.output_fields)}\n")
    for message in arm.call.messages():
        parts.append(f"\n## {message['role']}\n\n```text\n{message['content']}\n```\n")
    return "".join(parts)


def served_snapshot_text(arm: ServedArm) -> str:
    """The full committed snapshot of one condition's served first turn."""
    parts = [HEADER.format(condition=arm.condition.value, description=arm.description)]
    parts.append(SERVED_INTRO)
    parts.append(f"\nContract: `{arm.contract}`\n")
    if arm.options:
        parts.append(f"Request options: {sorted(arm.options)}\n")
    for message in arm.messages:
        parts.append(f"\n## {message['role']}\n\n```text\n{message['content']}\n```\n")
    return "".join(parts)


def snapshot_name(arm: Arm | ServedArm) -> str:
    """The file one arm's snapshot is committed as."""
    return f"{arm.condition.value}.md"
