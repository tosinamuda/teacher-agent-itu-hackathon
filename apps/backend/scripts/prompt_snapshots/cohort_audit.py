"""What the pipeline actually loaded for the frozen cohort, field by field.

The snapshots show what a condition sends for ONE synthetic lesson. This runs the same
rendering path over the real frozen eval set and asks a different question: for each real
lesson, did the fields a condition depends on actually arrive?

That matters more than any statistic. A projection drops a value it has nothing to put in
it — `_with_content` removes empty lists, dicts and strings — so a field the manipulation
rests on is simply ABSENT from the prompt when the teacher's plan had nothing for it, and
absent is indistinguishable from withheld once the prompt is rendered. If C1's fields did
not arrive, C1 was not the condition it was designed to be, and no amount of n would have
found a difference.

Runs on `eval_set.json`, which is the frozen record of the teacher's real plans. The
learner-state half of the cohort lives outside this repository and is reported as not
covered rather than silently omitted.
"""

from __future__ import annotations

import json
from collections import Counter
from dataclasses import dataclass

from app.domains.artefacts.types.post_class_review_pack.application.request.base.builder import (
    BaseReviewPackRequestBuilder,
)
from app.domains.artefacts.types.post_class_review_pack.application.request.source_content import (  # noqa: E501
    work_the_step_sets,
)
from app.domains.artefacts.types.post_class_review_pack.application.request.sources import (
    LessonSources,
)
from app.domains.artefacts.types.post_class_review_pack.infrastructure.dspy.generate_section import (  # noqa: E501
    GenerateSection,
)
from app.domains.experiments.domain.types import ConditionCode, Hypothesis
from app.domains.experiments.review_pack_study.conditions.profiles import profile_for
from app.shared.session_plan_view import SessionPlanView
from experiments.h1_condition_eval.dataset import EVAL_SET_PATH
from scripts.prompt_snapshots.arms import _UncallableLM
from scripts.prompt_snapshots.evidence import rendered_evidence
from scripts.prompt_snapshots.rendered import field_blocks, json_value

CONDITIONS = (ConditionCode.C0, ConditionCode.C1, ConditionCode.C2, ConditionCode.C3)

MANIPULATION_KEYS = (
    "lesson_context.entry_behaviour",
    "lesson_context.instructional_materials",
    "unit_context.current_step",
    "unit_context.instructional_events",
    "unit_context.student_tasks",
    "unit_context.assessment_points",
)
"""Every key C1 adds over C0. The whole of the H1a manipulation, per PROMPT-001C."""

CONTEXT_FIELDS = ("lesson_context", "unit_context")


@dataclass(frozen=True)
class LessonAudit:
    """One lesson under one condition: how many of its calls carried each key."""

    lesson: str
    condition: str
    units: int
    carrying: Counter
    evidence_units: int

    def carried(self, key: str) -> int:
        return self.carrying[key]


def frozen_lessons() -> dict[str, SessionPlanView]:
    """The teacher's plans, as the eval set froze them."""
    cases = json.loads(EVAL_SET_PATH.read_text(encoding="utf-8"))["cases"]
    return {case["lesson"]: SessionPlanView.model_validate(case["plan"]) for case in cases}


def audit_lesson(lesson: str, plan: SessionPlanView, condition: ConditionCode) -> LessonAudit:
    """Render every unit this condition would send for one lesson, and count what arrived."""
    request = BaseReviewPackRequestBuilder().build(
        session_plan=plan,
        policy=profile_for(Hypothesis.H1, condition).generation_policy(),
        sources=LessonSources.unresolved(plan.references),
    )
    generator = GenerateSection(lm=_UncallableLM())
    carrying: Counter = Counter()
    evidence_units = 0
    for unit in request.units:
        call = generator.prepared_call(request=request, unit=unit)
        blocks = field_blocks(call)
        for field in CONTEXT_FIELDS:
            value = json_value(blocks[field]) if field in blocks else {}
            if isinstance(value, dict):
                carrying.update(f"{field}.{key}" for key in value)
        evidence_units += bool(rendered_evidence(call))
    return LessonAudit(
        lesson=lesson,
        condition=condition.value,
        units=len(request.units),
        carrying=carrying,
        evidence_units=evidence_units,
    )


def audit() -> list[LessonAudit]:
    """Every lesson in the frozen set, under every H1 condition."""
    lessons = frozen_lessons()
    return [
        audit_lesson(lesson, plan, condition)
        for lesson, plan in lessons.items()
        for condition in CONDITIONS
    ]


AUDIT_DATE = "2026-08-14"
REPORT_PATH = EVAL_SET_PATH.parent / f"COHORT-INPUT-AUDIT-{AUDIT_DATE}.md"

_PREAMBLE = f"""# What the pipeline loaded for the frozen cohort — {AUDIT_DATE}

Generated by `uv run python -m scripts.prompt_snapshots.cohort_audit` from `eval_set.json`,
the frozen record of the teacher's real plans, through the same rendering path the prompt
snapshots use. No model is called.

The question is not whether C1 beat C0. It is whether C1 was ever the condition it was
designed to be. A projection drops a value it has nothing to put in, so a field the
manipulation rests on is simply ABSENT from the rendered prompt when the plan had nothing
for it — and once rendered, absent and withheld look identical.

**Not covered here:** the learner-state half. `learner_state` and `session_signals` come
from a separate store that lives outside this repository, so P0/P1 inputs are not audited
by this report. Named rather than silently omitted.
"""


def _delivery_table(audits: dict[tuple[str, str], LessonAudit], lessons: list[str]) -> str:
    total = sum(audits[(lesson, "C1")].units for lesson in lessons)
    rows = [
        "| Key C1 adds over C0 | " + " | ".join(lessons) + " | Cohort |",
        "| --- |" + " --- |" * (len(lessons) + 1),
    ]
    for key in MANIPULATION_KEYS:
        cells = [
            f"{audits[(lesson, 'C1')].carried(key)}/{audits[(lesson, 'C1')].units}"
            for lesson in lessons
        ]
        got = sum(audits[(lesson, "C1")].carried(key) for lesson in lessons)
        share = f"**{got}/{total}** ({got / total:.0%})"
        rows.append(f"| `{key}` | " + " | ".join(cells) + f" | {share} |")
    return "\n".join(rows)


def report() -> str:
    """The committed artefact: how much of the manipulation reached each real lesson."""
    audits = {(a.lesson, a.condition): a for a in audit()}
    lessons = sorted({lesson for lesson, _ in audits})
    parts = [
        _PREAMBLE,
        "\n## Did C1's manipulation arrive?\n",
        "Units carrying the key, per lesson. C0 receives none of these by design.\n",
        _delivery_table(audits, lessons),
        "\n\n## Evidence, the C2/C3 step\n",
        "| Lesson | " + " | ".join(c.value for c in CONDITIONS) + " |",
        "| --- |" + " --- |" * len(CONDITIONS),
    ]
    for lesson in lessons:
        cells = [
            f"{audits[(lesson, c.value)].evidence_units}/{audits[(lesson, c.value)].units}"
            for c in CONDITIONS
        ]
        parts.append(f"| {lesson} | " + " | ".join(cells) + " |")
    parts += ["\n## Why the thin rows are thin\n", _mechanism()]
    return "".join(part if part.endswith("\n") else part + "\n" for part in parts)


def _mechanism() -> str:
    """Counted from the plans, so the explanation is measured rather than asserted."""
    blocks: Counter = Counter()
    evaluation_steps = {}
    from_activity = 0
    for lesson, plan in frozen_lessons().items():
        core = [step for step in plan.steps if step.step_kind == "core"]
        blocks.update(str(block.get("type") or "?") for step in core for block in step.blocks)
        from_activity += sum(
            1
            for step in core
            if not any(block.get("type") == "practice" for block in step.blocks)
            and work_the_step_sets(step.activities)
        )
        evaluation_steps[lesson] = sum(1 for step in plan.steps if step.step_kind == "evaluation")
    kinds = ", ".join(f"`{kind}` {count}" for kind, count in sorted(blocks.items()))
    without = [lesson for lesson, count in sorted(evaluation_steps.items()) if not count]
    return (
        f"`student_tasks` carries the work a core step sets. Her questions come first: "
        f"across the cohort the core steps carry {sum(blocks.values())} blocks in total, "
        f"{kinds}, so {blocks['practice']} units can carry the field from a block.\n\n"
        f"Where a step has no question text the Student Activity column is read instead, "
        f"and only where her Gagne coder reads it as performance — a construction she set "
        f"has no question to carry it. That is {from_activity} further units. Reception "
        f'("listen", "take notes") is coded as nothing and crosses nowhere, and no '
        f"teacher activity crosses at all.\n\n"
        f"`assessment_points` reads the questions on an `evaluation` step. "
        f"{', '.join(without) or 'No lesson'} has none, which is why that row is empty "
        f"there.\n"
    )


def main() -> int:
    REPORT_PATH.write_text(report(), encoding="utf-8")
    print(f"wrote {REPORT_PATH.relative_to(EVAL_SET_PATH.parents[2])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
