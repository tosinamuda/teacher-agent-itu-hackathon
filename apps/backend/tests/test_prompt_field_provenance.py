"""Every field reaching the model has a traced source, and the map is read not typed.

For a field that arrived empty in the frozen cohort, the question is which step could have
emptied it. A hand-kept map answers that on the day it is written and lies after the first
refactor, so this one is derived from the projector source and regenerated by the same
command as the snapshots.

    uv run python -m scripts.prompt_snapshots
"""

from __future__ import annotations

import pytest

from scripts.prompt_snapshots import PROVENANCE_PATH
from scripts.prompt_snapshots.arms import every_arm
from scripts.prompt_snapshots.field_map import EVIDENCE_KEY, receiving_conditions
from scripts.prompt_snapshots.provenance import (
    STORES,
    FieldSource,
    field_sources,
    provenance_table,
    stores_for,
    untraced,
)
from scripts.prompt_snapshots.render import PROVENANCE_HEADER

SOURCES = field_sources()
BY_FIELD: dict[str, list[FieldSource]] = {}
for _source in SOURCES:
    BY_FIELD.setdefault(_source.field, []).append(_source)

# The evidence row stands for a whole list rather than one key, and the item's own fields
# are traced under SourceEvidenceItem.
RENDERED_KEYS = [
    key.split(".", 1)[1]
    for key in receiving_conditions(every_arm())
    if key != EVIDENCE_KEY and "." in key
]


def test_no_field_reaching_the_model_is_untraced() -> None:
    """A value with no accounted source is a finding, not an omission."""
    orphans = [
        f"{source.builder}.{source.field} = {source.expression}" for source in untraced(SOURCES)
    ]

    assert orphans == []


@pytest.mark.parametrize("key", sorted(set(RENDERED_KEYS)))
def test_every_rendered_prompt_key_appears_in_the_map(key: str) -> None:
    """The map covers what is actually sent, not what the schemas could carry."""
    assert key in BY_FIELD, f"{key} reaches the model and no builder was found for it"


def test_the_committed_map_matches_the_code() -> None:
    expected = PROVENANCE_HEADER + provenance_table() + "\n"

    assert PROVENANCE_PATH.exists(), "no committed provenance map"
    assert PROVENANCE_PATH.read_text(encoding="utf-8") == expected, (
        "the provenance map is stale — regenerate with `uv run python -m scripts.prompt_snapshots`"
    )


def test_the_map_is_derived_rather_than_declared() -> None:
    """Deleting a read from the projector must change the map, not just the code."""
    entry = next(s for s in SOURCES if s.field == "entry_behaviour")

    assert entry.reads == ("plan.entry_behaviour",)
    assert entry.expression.startswith("_project_text_items(")


def test_a_shared_helper_does_not_give_a_field_another_fields_source() -> None:
    """entry_behaviour and instructional_materials both go through _project_text_items."""
    entry = next(s for s in SOURCES if s.field == "entry_behaviour")
    materials = next(s for s in SOURCES if s.field == "instructional_materials")

    assert entry.reads == ("plan.entry_behaviour",)
    assert materials.reads == ("plan.instructional_materials",)


def test_the_evidence_step_is_traced_to_the_note_and_its_fallbacks() -> None:
    """PROMPT-001B pinned the fallback order; this says where each level reads from."""
    excerpt = next(s for s in SOURCES if s.field == "excerpt" and s.builder == "for_step")

    assert set(excerpt.reads) == {"step.note", "step.blocks", "step.step_id"}


def test_a_field_another_projector_owns_is_delegated_not_untraced() -> None:
    unit_evidence = [s for s in SOURCES if s.field == "source_evidence"]

    assert unit_evidence, "the unit's evidence field vanished from the map"
    assert all(s.origin == "delegated" for s in unit_evidence)
    assert any("_evidence.for_step" in s.delegated_to for s in unit_evidence)


def test_every_plan_rooted_field_names_the_store_it_is_parsed_from() -> None:
    for source in SOURCES:
        if source.origin != "traced":
            continue
        assert stores_for(source), f"{source.field} reads {source.reads} and names no store"


def test_the_lesson_and_the_learner_are_different_stores() -> None:
    """One absent plan payload empties every H1 field at once; learner state is separate,
    which is the distinction 002B has to make per learner and condition."""
    assert sum("session_plan" in store for store in STORES.values()) == 3
    assert sum("learner_state" in store for store in STORES.values()) == 4
