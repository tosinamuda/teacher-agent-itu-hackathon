"""Hold `docs/code-vocabulary.md` to the debt the tree actually carries.

Only the debt rows are asserted, and only in one direction. A ratchet is tolerable because a
cleanup never fails it; an equality assertion would fail both ways, so removing three `Port`
suffixes would break CI until someone edited a markdown table. Population counts (Stores,
Readers, port modules) grow with the product and have no target, so they are regenerated by
`scripts/code_vocabulary_census.py --write` and never asserted — asserting them would tax
every branch that adds a reader, which is how a guard earns its own deletion.
"""

from __future__ import annotations

import pytest

from scripts.code_vocabulary_census import (
    DEBT_CEILINGS,
    GRANDFATHERED_PORT_BUCKETS,
    POPULATION_KEYS,
    backlog_story_ids,
    census,
    documented_census,
    documented_exit_stories,
    domain_wide_port_buckets,
    exit_story_must_be_plannable,
    port_modules,
)

pytestmark = pytest.mark.architecture


def test_every_measured_count_is_documented() -> None:
    """A row may not quietly vanish from the table, whether debt or population."""
    assert set(documented_census()) == set(census())


def test_every_row_is_either_debt_or_population_and_never_both() -> None:
    """Classification is load-bearing, so a new row may not land unclassified.

    Debt is asserted and population is not, so the default a row falls into decides whether it
    can drift unnoticed. There is no third state.
    """
    debt, population = set(DEBT_CEILINGS), set(POPULATION_KEYS)
    assert debt | population == set(census()), "a census row is neither debt nor population"
    assert debt & population == set(), "a census row is declared both debt and population"


@pytest.mark.parametrize("key", sorted(DEBT_CEILINGS))
def test_every_debt_row_names_an_exit_story(key: str) -> None:
    stories = documented_exit_stories().get(key)
    assert stories, (
        f"{key} states a number with no owner. Name the story that deletes it in the row's "
        "Gap column, the way each import exemption names its exit."
    )


@pytest.mark.parametrize("key", sorted(DEBT_CEILINGS))
def test_an_open_rows_exit_story_exists_in_the_backlog(key: str) -> None:
    """Open debt must be plannable. A closed row names history, which may be archived."""
    known = backlog_story_ids()
    if known is None:
        pytest.skip("backlog is untracked and not checked out here")
    if not exit_story_must_be_plannable(census()[key]):
        pytest.skip(f"{key} is closed; its story is history rather than a plan")
    named = documented_exit_stories().get(key, [])
    assert set(named) <= known, f"{key} names {sorted(set(named) - known)}, absent from the backlog"


@pytest.mark.parametrize("key", sorted(DEBT_CEILINGS))
def test_debt_never_rises(key: str) -> None:
    measured = census()[key]
    assert measured <= DEBT_CEILINGS[key], (
        f"{key} rose to {measured} (ceiling {DEBT_CEILINGS[key]}). "
        "Lower it in the tree, or argue the ceiling up in this change."
    )


@pytest.mark.parametrize("key", sorted(DEBT_CEILINGS))
def test_documented_debt_is_not_stale(key: str) -> None:
    """A ceiling that has been beaten should be tightened, not left reading as current."""
    assert documented_census()[key] == census()[key], (
        f"{key} no longer matches the tree. "
        "Run `uv run python -m scripts.code_vocabulary_census --write` and lower the ceiling."
    )


def test_only_the_grandfathered_domain_wide_port_buckets_exist() -> None:
    """`<capability>_ports.py` is the shape; a bare `ports.py` is scoped to a whole domain."""
    assert domain_wide_port_buckets() <= GRANDFATHERED_PORT_BUCKETS, (
        "a new domain-wide `ports.py` appeared. Name it for the capability whose ports it "
        "declares — `launch_ports.py`, `rating_ports.py` — and put it beside its callers."
    )


def test_every_other_port_module_names_its_capability() -> None:
    named = [
        path.name
        for path in port_modules()
        if path.name != "ports.py" and not path.name.endswith("_ports.py")
    ]
    assert named == []
