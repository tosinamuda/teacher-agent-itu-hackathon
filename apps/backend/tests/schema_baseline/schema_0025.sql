CREATE TABLE `textbook_record_subtopics` (
  `id` char(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_as_cs NOT NULL,
  `record_id` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_as_cs NOT NULL,
  `subtopic_id` varchar(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_as_cs NOT NULL,
  `is_primary` tinyint(1) NOT NULL DEFAULT '0',
  `created_at` datetime NOT NULL DEFAULT (now()),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_textbook_record_subtopics_record_subtopic` (`record_id`,`subtopic_id`),
  KEY `ix_textbook_record_subtopics_subtopic_primary` (`subtopic_id`,`is_primary`),
  KEY `ix_textbook_record_subtopics_record_id` (`record_id`),
  KEY `ix_textbook_record_subtopics_subtopic_id` (`subtopic_id`),
  CONSTRAINT `textbook_record_subtopics_ibfk_1` FOREIGN KEY (`record_id`) REFERENCES `textbook_records` (`record_id`) ON DELETE CASCADE,
  CONSTRAINT `textbook_record_subtopics_ibfk_2` FOREIGN KEY (`subtopic_id`) REFERENCES `curriculum_subtopics` (`subtopic_id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
